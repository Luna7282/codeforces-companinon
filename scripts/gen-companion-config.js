#!/usr/bin/env node
/*
 * Generates browser/deeplink-config.js from the extension's own package.json,
 * so the companion's vscode:// URI and Marketplace fallback link are derived
 * from the real publisher/name — never hardcoded, so publishing later is a
 * config change (bump the version / register the publisher), not a code change.
 *
 * Run after cloning, and after changing "publisher" or "name" in package.json.
 * `npm run build:companion` runs this automatically.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf8'));
const { publisher, name } = pkg;
if (!publisher || !name) {
    console.error('package.json is missing "publisher" or "name" — cannot generate the deep link config.');
    process.exit(1);
}

const extensionId = `${publisher}.${name}`;
const out = `// AUTO-GENERATED by scripts/gen-companion-config.js from package.json (publisher: "${publisher}", name: "${name}").
// Do not edit by hand — re-run "npm run gen:companion-config" instead.
// Loaded by both content.js (page context) and background.js (importScripts).
var CF_DEEPLINK = {
    uriBase: 'vscode://${extensionId}',
    marketplaceUrl: 'https://marketplace.visualstudio.com/items?itemName=${extensionId}'
};
`;

fs.writeFileSync(path.join(__dirname, '..', 'browser', 'deeplink-config.js'), out, 'utf8');
console.log(`wrote browser/deeplink-config.js for ${extensionId}`);
